"""Copy a pinned, clean CAD source revision. No samples, runtimes or caches."""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

repo = Path(sys.argv[1]).resolve()
revision = sys.argv[2]
commit = subprocess.check_output(['git', '-C', str(repo), 'rev-parse', revision], text=True).strip()
prefix = '10_独立解析查看器/'
base = Path(__file__).resolve().parent
frontend = base.parents[1] / 'frontend/public/cad-viewer/core'
files = subprocess.check_output(['git', '-C', str(repo), 'ls-tree', '-r', '--name-only', '-z', commit, prefix], text=True).split('\0')
engine = {}
browser = {}
for name in files:
    if not name:
        continue
    relative = name.removeprefix(prefix)
    allowed = relative == 'step_convert.py' or relative.startswith('unified/') and relative.endswith(('.py', '.json'))
    if not allowed and not relative.startswith('public/'):
        continue
    if relative.startswith('public/') and not (relative.endswith(('.js', '.css', '.txt', '.md')) or Path(relative).name == 'LICENSE'):
        continue
    raw = subprocess.check_output(['git', '-C', str(repo), 'show', commit + ':' + name])
    destination = frontend / relative.removeprefix('public/') if relative.startswith('public/') else base / 'core' / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(raw)
    (browser if relative.startswith('public/') else engine)[relative.removeprefix('public/') if relative.startswith('public/') else relative] = hashlib.sha256(raw).hexdigest()
for name in ('requirements-step.txt', 'requirements-step-mesher.txt'):
    raw = subprocess.check_output(['git', '-C', str(repo), 'show', commit + ':' + prefix + name])
    (base / name).write_bytes(raw)
release = {'sourceCommit': commit, 'stepRelease': '0.3.3', 'gatewayProtocol': 'libiaolink-cad-gateway/1',
           'engineFiles': engine, 'browserFiles': browser}
if not engine or not browser:
    raise RuntimeError('Missing CAD source files')
(base / 'source.json').write_text(json.dumps(release, ensure_ascii=False, indent=2) + '\n')
version = 'step-' + release['stepRelease'] + '/' + commit + '/gateway-1'
(base.parent / 'src/modules/file/cad-release.ts').write_text('// Generated by cad-engine/sync-source.py; do not edit.\nexport const CAD_ENGINE_VERSION = ' + json.dumps(version) + ';\n')
print('Copied pinned CAD engine:', commit, 'engine files:', len(engine), 'browser files:', len(browser))
