/** 英文月份缩写（日期文案用；Push 301）。 */
const EN_MONTHS: readonly string[] = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** 日期文案（ISO YYYY-MM-DD）：中文 = 「9月5日」；英文 = 「Sep 5」；空值 / 非法值返回空串。 */
export function mdText(locale: Locale, iso: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (match === null) {
    return "";
  }
  const month = Number(match[2]);
  const day = Number(match[3]);
  return locale === "en" ? EN_MONTHS[month - 1] + " " + String(day) : String(month) + "月" + String(day) + "日";
}

