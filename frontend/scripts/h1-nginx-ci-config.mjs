#!/usr/bin/env node
/**
 * 从生产 Nginx 配置生成 H1 S6 CI 派生配置。
 *
 * 派生只替换运行位置，不另写一套安全响应头：CI 因而持续覆盖
 * deploy/prod/nginx/libiaolink.conf 的 HSTS / CSP / XFO / nosniff 与
 * /api/v1、/libiaolink/、/onlyoffice/、SPA 的路由关系。生产服务名与容器 DNS
 * 仅在此处按本机回环替换。
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, "..", "..");
const SOURCE = path.join(REPO_ROOT, "deploy", "prod", "nginx", "libiaolink.conf");
const OUT = process.env.H1_NGINX_CONF_OUT ?? "/tmp/h1-nginx.conf";
const CERT = process.env.H1_NGINX_CERT ?? "/tmp/h1-certs/localhost.pem";
const KEY = process.env.H1_NGINX_KEY ?? "/tmp/h1-certs/localhost-key.pem";
const WEB_ROOT = process.env.H1_NGINX_WEB_ROOT ?? path.join(REPO_ROOT, "frontend", "dist");
const ACCESS_LOG = process.env.H1_NGINX_ACCESS_LOG ?? "/tmp/h1-nginx-access.log";
const ERROR_LOG = process.env.H1_NGINX_ERROR_LOG ?? "/tmp/h1-nginx-error.log";
const PID = process.env.H1_NGINX_PID ?? "/tmp/h1-nginx.pid";

function replaceOrThrow(text, from, to, label) {
  if (!text.includes(from)) {
    throw new Error("生产 Nginx 配置缺少预期片段（" + label + "），拒绝生成可能与生产漂移的 CI 配置");
  }
  return text.split(from).join(to);
}

function paths(value) {
  return value.replaceAll("\\", "/").replaceAll('"', "'");
}

let source = await readFile(SOURCE, "utf8");
source = replaceOrThrow(source, "server api:3000 resolve;", "server 127.0.0.1:3011;", "api upstream");
source = replaceOrThrow(source, "server minio:9000 resolve;", "server 127.0.0.1:9000;", "minio upstream");
source = replaceOrThrow(source, "server libiaolink-onlyoffice-docs:80 resolve;", "server 127.0.0.1:8001;", "onlyoffice upstream");
source = replaceOrThrow(source, "/etc/nginx/ssl/libiaorobot.com.pem", paths(CERT), "cert");
source = replaceOrThrow(source, "/etc/nginx/ssl/libiaorobot.com.key", paths(KEY), "key");
source = replaceOrThrow(source, "root /srv/www;", 'root "' + paths(WEB_ROOT) + '";', "SPA root");
source = source.replace(/^resolver\s+127\.0\.0\.11[^;]*;\s*$/gm, "");
// Ubuntu runner 的 nginx 可能低于生产镜像；TCP 路由与安全头回归不依赖 HTTP/2。
source = source.replace(/^\s*http2\s+on;\s*$/gm, "");
source = source.split("test-pm.libiaorobot.com").join("localhost");

const unknownSni = source.indexOf("# ---- 443 兜底");
if (unknownSni >= 0) {
  source = source.slice(0, unknownSni);
}

for (const directory of [
  path.dirname(OUT),
  "/tmp/h1-nginx-client",
  "/tmp/h1-nginx-proxy",
  "/tmp/h1-nginx-fastcgi",
  "/tmp/h1-nginx-uwsgi",
  "/tmp/h1-nginx-scgi",
]) {
  await mkdir(directory, { recursive: true });
}

const wrapper = `# Generated by frontend/scripts/h1-nginx-ci-config.mjs from production config.
worker_processes 1;
pid ${paths(PID)};
error_log ${paths(ERROR_LOG)} warn;

events {
  worker_connections 1024;
}

http {
  include /etc/nginx/mime.types;
  default_type application/octet-stream;
  # 刻意不记录 query string：预签名参数不得进入 CI artifact。
  log_format h1_redacted '$remote_addr - $remote_user [$time_local] "$request_method $uri $server_protocol" '
                         '$status $body_bytes_sent "$http_referer" "$http_user_agent"';
  access_log ${paths(ACCESS_LOG)} h1_redacted;
  client_body_temp_path /tmp/h1-nginx-client;
  proxy_temp_path /tmp/h1-nginx-proxy;
  fastcgi_temp_path /tmp/h1-nginx-fastcgi;
  uwsgi_temp_path /tmp/h1-nginx-uwsgi;
  scgi_temp_path /tmp/h1-nginx-scgi;

${source.trim()}
}
`;

await writeFile(OUT, wrapper, "utf8");
process.stdout.write(OUT + "\n");
